let currentLang = 'en';

function readStoredLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && translations[saved]) return saved;
  } catch (e) {
    // ignore
  }
  return 'en';
}

function updateMeta(lang) {
  const dict = translations[lang];
  if (!dict) return;
  const og = document.querySelector('meta[property="og:locale"]');
  const tw = document.querySelector('meta[name="twitter:locale"]');
  if (og && dict['meta.ogLocale'] != null) og.setAttribute('content', dict['meta.ogLocale']);
  if (tw && dict['meta.twitterLocale'] != null) tw.setAttribute('content', dict['meta.twitterLocale']);
}

function applyTranslations(lang) {
  document.documentElement.setAttribute('lang', lang);
  updateMeta(lang);
  const dict = translations[lang];
  if (!dict) return;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] != null) {
      el.textContent = dict[key];
    }
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] != null) {
      el.innerHTML = dict[key];
    }
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria-label');
    if (dict[key] != null) {
      el.setAttribute('aria-label', dict[key]);
    }
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const key = el.getAttribute('data-i18n-alt');
    if (dict[key] != null) {
      el.setAttribute('alt', dict[key]);
    }
  });
  document.querySelectorAll('[data-i18n-content]').forEach((el) => {
    const key = el.getAttribute('data-i18n-content');
    if (dict[key] != null) {
      el.setAttribute('content', dict[key]);
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] != null) {
      el.setAttribute('placeholder', dict[key]);
    }
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key] != null) {
      el.setAttribute('title', dict[key]);
    }
  });
}

/** The current language code ('en', 'tr', 'es', …). */
export function getLang() {
  return currentLang;
}

/**
 * Look up a translation for the current language. Returns the key itself when
 * no translation exists, which makes missing strings easy to spot.
 */
export function t(key) {
  return translations[currentLang]?.[key] ?? translations.en[key] ?? key;
}

export function initI18n() {
  currentLang = readStoredLang();
  applyTranslations(currentLang);
  // Language selection lives in the flag dropdown (common.js), which stores
  // the choice and reloads the page — so applying the stored language above
  // is all this module must do on load. This listener keeps an in-place
  // switch in sync too (panelui.js re-renders on the same event).
  document.addEventListener('owlaso:langchange', (e) => {
    const lang = e.detail?.lang;
    if (lang && translations[lang] && lang !== currentLang) {
      currentLang = lang;
      applyTranslations(lang);
    }
  });
}
